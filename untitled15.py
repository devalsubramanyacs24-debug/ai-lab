facts = {
    ("American", "Robert"),
    ("Enemy", "A", "America"),
    ("Owns", "A", "T1"),
    ("Missile", "T1")
}

def forward_chaining(facts):

    while True:
        new_facts = set()

        for f in facts:
            if f[0] == "Missile":
                new_facts.add(("Weapon", f[1]))

        for f in facts:
            if f[0] == "Enemy" and f[2] == "America":
                new_facts.add(("Hostile", f[1]))

        for m in facts:
            if m[0] == "Missile":
                for o in facts:
                    if o[0] == "Owns" and o[1] == "A" and o[2] == m[1]:
                        new_facts.add(("Sells", "Robert", m[1], "A"))

        for a in facts:
            if a[0] == "American":
                for w in facts:
                    if w[0] == "Weapon":
                        for s in facts:
                            if s[0] == "Sells":
                                for h in facts:
                                    if (s[1] == a[1] and
                                        s[2] == w[1] and
                                        s[3] == h[1] and
                                        h[0] == "Hostile"):
                                        new_facts.add(("Criminal", a[1]))

        new_facts = new_facts - facts

        if not new_facts:
            break

        facts.update(new_facts)

        for f in new_facts:
            print(f)

        if ("Criminal", "Robert") in facts:
            print("\nGoal Proved: Robert is Criminal")
            return True

    return False

forward_chaining(facts)

