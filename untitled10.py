import random
import math


N = 8


def initial_state():
    state = list(range(N))
    random.shuffle(state)
    return state


def calculate_cost(state):
    cost = 0

    for i in range(N):
        for j in range(i + 1, N):
            if abs(state[i] - state[j]) == abs(i - j):
                cost += 1

    return cost


def get_neighbour(state):
    new_state = state.copy()

    i, j = random.sample(range(N), 2)

    new_state[i], new_state[j] = new_state[j], new_state[i]

    return new_state


def simulated_annealing():

    current_state = initial_state()
    current_cost = calculate_cost(current_state)

    temperature = 100
    cooling_rate = 0.95
    min_temperature = 0.001

    iteration = 0

    print("Initial State:", current_state)
    print("Initial Cost:", current_cost)

    while temperature > min_temperature:

        for _ in range(100):

            neighbour = get_neighbour(current_state)
            neighbour_cost = calculate_cost(neighbour)

            delta = neighbour_cost - current_cost


            if delta < 0:
                current_state = neighbour
                current_cost = neighbour_cost


            elif random.random() < math.exp(-delta / temperature):
                current_state = neighbour
                current_cost = neighbour_cost

            iteration += 1


            if iteration % 500 == 0:
                print("Iteration:", iteration,
                      "Temperature:", round(temperature, 4),
                      "Cost:", current_cost)


            if current_cost == 0:
                print("\nSolution Found!")
                print("Final State:", current_state)
                print("Final Cost:", current_cost)
                print("Total Iterations:", iteration)
                return current_state


        temperature *= cooling_rate

    print("\nNo solution found in this run.")
    print("Final State:", current_state)
    print("Final Cost:", current_cost)

    return None



solution = None

for attempt in range(1, 21):
    print("\n========== Attempt", attempt, "==========")

    solution = simulated_annealing()

    if solution is not None:
        break

if solution is None:
    print("\nTry increasing the number of attempts.")
else:
    print("\n8 Queens Solution:", solution)



