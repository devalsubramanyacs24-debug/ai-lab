def is_variable(x):
    return isinstance(x, str) and x.islower()


def occurs_check(var, expr, subst):
    expr = substitute(expr, subst)

    if var == expr:
        return True

    if isinstance(expr, list) or isinstance(expr, tuple):
        return any(occurs_check(var, item, subst) for item in expr)

    return False


def substitute(expr, subst):
    if isinstance(expr, str):
        while expr in subst:
            expr = subst[expr]
        return expr

    if isinstance(expr, (list, tuple)):
        return type(expr)(substitute(item, subst) for item in expr)

    return expr


def unify(x, y, subst=None):
    if subst is None:
        subst = {}

    x = substitute(x, subst)
    y = substitute(y, subst)

    if x == y:
        return subst


    if is_variable(x):
        if occurs_check(x, y, subst):
            return None

        subst[x] = y
        return subst

    if is_variable(y):
        if occurs_check(y, x, subst):
            return None

        subst[y] = x
        return subst

    if not isinstance(x, (list, tuple)) or not isinstance(y, (list, tuple)):
        return None

    if len(x) != len(y):
        return None

    if x[0] != y[0]:
        return None

    for a, b in zip(x[1:], y[1:]):
        result = unify(a, b, subst)

        if result is None:
            return None

        subst = result

    return subst


