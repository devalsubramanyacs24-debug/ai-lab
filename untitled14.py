def parse(lit):
    neg = lit.startswith('~')
    pred, args = (lit[1:] if neg else lit)[:-1].split('(')
    return neg, pred, args.split(',')

def unify(a1, a2):
    subs = {}
    for x, y in zip(a1, a2):
        if x == y: continue
        if x.islower(): subs[x] = y
        elif y.islower(): subs[y] = x
        else: return None
    return subs

def apply_subs(clause, subs):
    res = []
    for lit in clause:
        neg, pred, args = parse(lit)
        new_args = [subs.get(a, a) for a in args]
        res.append(f"{'~' if neg else ''}{pred}({','.join(new_args)})")
    return list(dict.fromkeys(res))

def resolve(c1, c2):
    for l1 in c1:
        n1, p1, a1 = parse(l1)
        for l2 in c2:
            n2, p2, a2 = parse(l2)
            if p1 == p2 and n1 != n2:
                subs = unify(a1, a2)
                if subs is not None:
                    rem = [l for l in c1 if l != l1] + [l for l in c2 if l != l2]
                    return apply_subs(rem, subs)
    return None

def prove(kb, negated_goal):
    queue = [negated_goal]
    step = 1
    while queue:
        curr = queue.pop(0)
        for clause in kb:
            res = resolve(curr, clause)
            if res is not None:
                print(f"{step}. {' | '.join(res) if res else '[] -> PROVED'}")
                step += 1
                if not res: return
                queue.append(res)

KB = [
    ["~Food(x)", "Likes(John,x)"],
    ["Food(Apple)"],
    ["Food(Vegetables)"],
    ["~Eats(x,y)", "Killed(x)", "Food(y)"],
    ["Eats(Anil,Peanuts)"],
    ["Alive(Anil)"],
    ["~Eats(Anil,x)", "Eats(Harry,x)"],
    ["~Alive(x)", "~Killed(x)"],
    ["Killed(x)", "Alive(x)"]
]

prove(KB, ["~Likes(John,Peanuts)"])

